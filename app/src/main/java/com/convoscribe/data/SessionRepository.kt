package com.convoscribe.data

import androidx.room.withTransaction
import com.convoscribe.recording.RecordingStore
import java.io.File
import kotlinx.coroutines.flow.Flow

/**
 * Façade over [AppDatabase] for the rest of the app. Callers do not
 * touch the DAOs directly: this class owns the transactional rules
 * (e.g. applying a diarization result writes the per-segment speaker
 * index, replaces the speaker labels and flips the session status in
 * one transaction) and the on-disk side effects (the WAV file is
 * removed when the session is deleted).
 *
 * [recordingsDir] is `filesDir/recordings`; every session points at
 * `<recordingsDir>/<id>.wav` and that file is owned by this class
 * for the lifetime of the session.
 *
 * Also implements [RecordingStore] so the recording controller can
 * drive a session without taking a hard dependency on Room: the
 * controller talks to the interface and the production wiring
 * passes this repository.
 */
class SessionRepository(
    private val db: AppDatabase,
    private val recordingsDir: File
) : RecordingStore {
    private val sessionDao: SessionDao = db.sessionDao()
    private val segmentDao: SegmentDao = db.segmentDao()
    private val speakerDao: SpeakerDao = db.speakerDao()
    private val chatMessageDao: ChatMessageDao = db.chatMessageDao()

    /**
     * Create a new session row with [status] = RECORDING and
     * `audioPath = <recordingsDir>/<id>.wav`. The two writes happen
     * separately (insert first so we know the id, then update to
     * stamp the path) because the path depends on the autogenerated
     * primary key. The returned id is what the recorder uses to
     * create the WAV file.
     */
    override suspend fun createSession(title: String, language: String): Long {
        val now = System.currentTimeMillis()
        val id = sessionDao.insert(
            SessionEntity(
                title = title,
                createdAt = now,
                language = language,
                status = SessionStatus.RECORDING
            )
        )
        val audioPath = File(recordingsDir, "$id.wav").absolutePath
        sessionDao.update(
            SessionEntity(
                id = id,
                title = title,
                createdAt = now,
                language = language,
                status = SessionStatus.RECORDING,
                audioPath = audioPath
            )
        )
        return id
    }

    /**
     * Append a transcript segment. Called by the ASR engine as
     * endpoints are detected. Returns the new segment id.
     */
    override suspend fun addSegment(sessionId: Long, startMs: Long, endMs: Long, text: String): Long =
        segmentDao.insert(
            SegmentEntity(
                sessionId = sessionId,
                startMs = startMs,
                endMs = endMs,
                text = text
            )
        )

    /**
     * Recording finished. Stamp the duration and move the session
     * to [SessionStatus.TRANSCRIBED] so the diarization worker picks
     * it up.
     */
    override suspend fun finishRecording(sessionId: Long, durationMs: Long) {
        sessionDao.get(sessionId)?.let { row ->
            sessionDao.update(
                row.copy(
                    durationMs = durationMs,
                    status = SessionStatus.TRANSCRIBED
                )
            )
        }
    }

    /**
     * Look up the WAV path the recorder should write to for
     * [sessionId]. Returns the `audioPath` column stamped by
     * [createSession]. Throws [IllegalStateException] if the
     * session is unknown: that should never happen because the
     * recorder only calls this with an id returned by
     * [createSession] moments earlier, and we want a loud failure
     * instead of a silent default.
     */
    override suspend fun audioPath(sessionId: Long): String {
        val row = sessionDao.get(sessionId)
            ?: error("No session row for id $sessionId; was it deleted mid-recording?")
        return row.audioPath
    }

    /**
     * Delete the session, the WAV file and (via `ON DELETE CASCADE`)
     * the segments, speakers and chat messages. Idempotent: deleting
     * an unknown id is a no-op and silently returns.
     */
    suspend fun deleteSession(id: Long) {
        val row = sessionDao.get(id)
        if (row != null) {
            val audio = File(row.audioPath)
            if (audio.exists()) {
                audio.delete()
            }
        }
        sessionDao.delete(id)
    }

    // --- Pass-throughs for observe/get ---

    fun observeAllSessions(): Flow<List<SessionEntity>> = sessionDao.observeAll()

    fun observeSession(id: Long): Flow<SessionEntity?> = sessionDao.observe(id)

    suspend fun getSession(id: Long): SessionEntity? = sessionDao.get(id)

    fun observeSegments(sessionId: Long): Flow<List<SegmentEntity>> = segmentDao.observeForSession(sessionId)

    suspend fun getSegments(sessionId: Long): List<SegmentEntity> = segmentDao.getForSession(sessionId)

    fun observeSpeakers(sessionId: Long): Flow<List<SpeakerEntity>> = speakerDao.observeForSession(sessionId)

    suspend fun getSpeakers(sessionId: Long): List<SpeakerEntity> = speakerDao.getForSession(sessionId)

    fun observeChat(sessionId: Long, kind: MessageKind): Flow<List<ChatMessageEntity>> =
        chatMessageDao.observe(sessionId, kind)

    suspend fun deleteChatKind(sessionId: Long, kind: MessageKind) = chatMessageDao.deleteKind(sessionId, kind)

    suspend fun addChatMessage(entity: ChatMessageEntity): Long = chatMessageDao.insert(entity)

    suspend fun setSegmentSpeaker(segmentId: Long, speakerIndex: Int?) = segmentDao.setSpeaker(segmentId, speakerIndex)

    suspend fun renameSpeaker(sessionId: Long, speakerIndex: Int, label: String) =
        speakerDao.rename(sessionId, speakerIndex, label)

    /**
     * Flip [id]'s status to [status]. Used by the diarization use
     * case (`DIARIZING` on entry, `DIARIZED` via
     * [applyDiarization], `DIARIZATION_FAILED` on error) and by
     * the crash-recovery loop (`RECORDING`/`DIARIZING` →
     * `TRANSCRIBED`). Unknown ids are a no-op because the DAO's
     * `UPDATE` statement does nothing on a missing row.
     */
    suspend fun setStatus(id: Long, status: SessionStatus) {
        sessionDao.setStatus(id, status)
    }

    /**
     * Stamp [durationMs] on [id]. Used by the crash-recovery loop
     * to compute the duration of a WAV that was left in a
     * half-closed state when the process was killed; the recorder
     * itself calls [finishRecording], which both sets the duration
     * and flips the status. Unknown ids are a no-op.
     */
    suspend fun setDuration(id: Long, durationMs: Long) {
        sessionDao.updateDuration(id, durationMs)
    }

    /**
     * Every session currently in [status]. Used by the
     * crash-recovery loop (TASK-19) to find sessions left in
     * `RECORDING` (process killed mid-capture) or `DIARIZING`
     * (process killed mid-diarization). The result is a snapshot
     * taken at call time — the loop iterates it without holding
     * any database cursor, so the writes it issues do not race
     * with a future caller re-fetching the same rows.
     */
    suspend fun sessionsWithStatus(status: SessionStatus): List<SessionEntity> {
        return sessionDao.findByStatus(status)
    }

    /**
     * Persist a diarization result. [assignments] maps a segment id
     * to its speaker index (or `null` for unlabelled). [speakerCount]
     * is the number of distinct speakers the diarizer detected, used
     * to generate the "Speaker 1..N" labels.
     *
     * Everything happens in one transaction so a crash mid-write
     * does not leave the session half-diarized: either every
     * segment has the new index and the speakers table is replaced,
     * or nothing changed.
     */
    suspend fun applyDiarization(sessionId: Long, assignments: Map<Long, Int?>, speakerCount: Int) {
        db.withTransaction {
            assignments.forEach { (segmentId, speakerIndex) ->
                segmentDao.setSpeaker(segmentId, speakerIndex)
            }
            speakerDao.deleteForSession(sessionId)
            val rows = (0 until speakerCount).map { i ->
                SpeakerEntity(
                    sessionId = sessionId,
                    speakerIndex = i,
                    label = "Speaker ${i + 1}"
                )
            }
            if (rows.isNotEmpty()) {
                speakerDao.upsert(rows)
            }
            sessionDao.setStatus(sessionId, SessionStatus.DIARIZED)
        }
    }
}
